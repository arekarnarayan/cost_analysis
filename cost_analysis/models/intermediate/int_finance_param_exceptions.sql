{{ config(materialized='view') }}

SELECT
    *,
    CASE
        WHEN PARAMETER IS NULL
            THEN 'MISSING_PARAMETER'
        WHEN BUSINESS_VALID_FROM IS NULL
            THEN 'INVALID_BUSINESS_DATE'
        WHEN SOURCE_VALUE IS NULL
            THEN 'MISSING_VALUE'
        WHEN PARAMETER_VALUE IS NULL
            THEN 'INVALID_NUMERIC_VALUE'
        ELSE 'UNKNOWN_VALIDATION_FAILURE'
    END AS EXCEPTION_REASON

FROM {{ ref('stg_finance_params') }}

WHERE PARAMETER IS NULL
   OR BUSINESS_VALID_FROM IS NULL
   OR SOURCE_VALUE IS NULL
   OR PARAMETER_VALUE IS NULL